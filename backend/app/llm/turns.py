"""Which threads have a turn running right now, in this process.

A turn is generated by a task that outlives the request that started it (api/threads.send_message):
a browser that navigates away mid-reply closes its connection, but the reply is still written to the
thread. This registry lets a reload say "Astra is still replying" instead of showing a question with
no answer.

It is in memory, so it is exact for the replica that is running the turn and says nothing about
another replica's. The browser therefore also treats "the last message is mine and recent" as a
reason to look again (see frontend/app/workspace/[id]/page.tsx); it never claims more than that.
"""
from __future__ import annotations

import uuid

_active: dict[uuid.UUID, int] = {}


def begin(thread_id: uuid.UUID) -> None:
    _active[thread_id] = _active.get(thread_id, 0) + 1


def end(thread_id: uuid.UUID) -> None:
    left = _active.get(thread_id, 0) - 1
    if left > 0:
        _active[thread_id] = left
    else:
        _active.pop(thread_id, None)


def is_active(thread_id: uuid.UUID) -> bool:
    return thread_id in _active
